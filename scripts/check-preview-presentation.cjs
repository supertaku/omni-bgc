const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (mod, filename) => mod._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true, resolveJsonModule: true } }).outputText, filename);
const { displayFoodPrice, createFoodResearchService } = require('../src/features/food/service.ts');
const raw = require('../assets/generated/food-research/directory.json');
const estimated = raw.restaurants.flatMap(r => r.items).find(i => i.priceEvidence === 'estimated');
assert.equal(displayFoodPrice(estimated, false), null, 'strict policy retains evidence gate');
assert.ok(displayFoodPrice(estimated, true), 'preview displays valid estimated amounts');
assert.equal(displayFoodPrice({ ...estimated, amount: '-1' }, true), null);
assert.equal(displayFoodPrice({ ...estimated, currency: 'USD' }, true), null);
const strict = createFoodResearchService(raw, false);
const preview = createFoodResearchService(raw, true);
assert.equal(strict.searchFoodMenuItems({ restaurantId: estimated.restaurantId, maxPhp: '999999' }).results.some(r => r.item.id === estimated.id), false);
assert.equal(preview.searchFoodMenuItems({ restaurantId: estimated.restaurantId, maxPhp: '999999' }).results.some(r => r.item.id === estimated.id), true);
const { resolveCurrentPlace } = require('../src/features/explore/placeOpening.ts');
const directory = require('../src/preview/directory.ts');
const { foodResearch, foodPlaces } = require('../src/features/food/directory.ts');
const { browsingPlaces } = require('../src/features/explore/directory.ts');
const { resolveMapResultRecords } = require('../src/features/assistant/mapResults.ts');
const { officeFocus, setOfficeMapScope } = require('../src/features/offices/map.ts');
const { pilotScope, coverageAt } = require('../src/map/scope.ts');
assert.ok(directory.previewAvailable, 'shipped overlay actually passes runtime validation');
assert.ok(foodResearch.available && foodResearch.restaurants.every(r => r.items.length >= 8));
const all = browsingPlaces([]);
assert.equal(all.length, new Set(all.map(p => p.id)).size, 'one rendered place per canonical ID');
assert.ok(all.some(p => p.category === 'office' && p.preview), 'release preview contains offices');
const office = directory.previewPlaces.find(p => p.category === 'office' && p.coordinate);
assert.ok(office);
setOfficeMapScope(pilotScope);
assert.deepEqual(officeFocus(office), coverageAt(pilotScope, office.coordinate) === 'service' ? office.coordinate : null, 'active pack controls camera focus, never place identity');
setOfficeMapScope(null);
assert.equal(officeFocus(office), null, 'camera waits for a usable map scope');
(async () => {
  const candidate = { id: 'local', status: 'candidate', coordinate: null };
  assert.equal(await resolveCurrentPlace('local', [candidate], async () => null), candidate);
  assert.equal(await resolveCurrentPlace('removed', [], async () => null), null);
  const approved = { id: 'approved', status: 'approved' };
  assert.equal(await resolveCurrentPlace('approved', [approved], async () => null), null, 'stale approved snapshots cannot grant authority');
  assert.equal(await resolveCurrentPlace('approved', [approved], async () => approved), approved);
  const known = directory.previewPlaces.find(p => p.category !== 'office');
  const freshApproved = { ...known, status:'approved', description:undefined, imageKey:undefined, preview:undefined };
  const openedApproved = await resolveCurrentPlace(known.id, [directory.enrichPreviewPlace(freshApproved)], async () => freshApproved);
  assert.equal(openedApproved.description, known.description, 'fresh approved places retain presentation enrichment');
  assert.equal(openedApproved.imageKey, known.imageKey);
  assert.equal(openedApproved.status, 'approved');
  const restaurant = foodResearch.restaurants[0], item = restaurant.items[0];
  const owner = await resolveCurrentPlace(item.id, all, async () => null);
  assert.equal(owner.id, directory.canonicalPreviewId(restaurant.id), 'menu opens its canonical establishment');
  const rows = await resolveMapResultRecords([item.id, restaurant.id], all, async () => null);
  assert.equal(rows.length, 1, 'related assistant identities share one highlighted place');
  assert.ok(foodPlaces.some(p => p.id === owner.id));
  const unlocated = all.find(p => p.preview && !p.coordinate);
  assert.ok(unlocated && await resolveCurrentPlace(unlocated.id, all, async () => null), 'unlocated places still open details');
  console.log('Preview presentation: explicit price policies, centavos, currency and fresh place resolution passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
