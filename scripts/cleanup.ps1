param(
  [string]$Manifest = '.g/cleanup/deletion-manifest.json',
  [switch]$Apply,
  [switch]$IncludeWorktree
)
$ErrorActionPreference = 'Stop'
$repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$manifestPath = [IO.Path]::GetFullPath((Join-Path $repoRoot $Manifest))
$evidenceRoot = Join-Path $repoRoot '.g/cleanup'
if (-not $manifestPath.StartsWith($evidenceRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
  throw 'Manifest must be inside the repository cleanup evidence directory.'
}
if ([IO.Path]::GetFileName($manifestPath) -ne 'deletion-manifest.json') {
  throw 'Use a deletion-manifest.json generated by scripts/cleanup.py.'
}
$runEvidence = Split-Path -Parent $manifestPath
$inventory = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
if ($inventory.root -ne $repoRoot) { throw 'Manifest belongs to a different repository.' }
Push-Location $repoRoot
try {
  if ($Apply) { & python scripts/cleanup.py --evidence $runEvidence --validate-manifest --preflight }
  else { & python scripts/cleanup.py --evidence $runEvidence --validate-manifest }
  if ($LASTEXITCODE -ne 0) { throw 'Manifest validation failed.' }
  if ($Apply) {
    & python scripts/cleanup.py --evidence $runEvidence --verify
    if ($LASTEXITCODE -ne 0) { throw 'Retained files failed checksum verification.' }
    $preflight = Get-Content -LiteralPath (Join-Path $runEvidence 'deletion-preflight.json') -Raw | ConvertFrom-Json
  }
  foreach ($target in $inventory.targets) {
    $absolute = [IO.Path]::GetFullPath((Join-Path $repoRoot $target.path))
    if (-not $absolute.StartsWith($repoRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
      throw "Deletion target escapes the repository: $absolute"
    }
    if (-not (Test-Path -LiteralPath $absolute)) { continue }
    if (-not $Apply) { Write-Output "DRY RUN: $($target.path) ($($target.bytes) bytes)"; continue }
    # The complete preflight enumerated and checked links without following
    # them. Detach only those recorded links instead of enumerating every npm
    # file again through the PowerShell provider.
    foreach ($relativeLink in $preflight.links) {
      if ($relativeLink.StartsWith($target.path + '/', [StringComparison]::OrdinalIgnoreCase)) {
        $linkPath = [IO.Path]::GetFullPath((Join-Path $repoRoot $relativeLink))
        if (-not $linkPath.StartsWith($absolute + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
          throw 'Link removal escapes its validated target.'
        }
        if (Test-Path -LiteralPath $linkPath) { Remove-Item -LiteralPath $linkPath -Force }
      }
    }
    if ($target.path -eq '.g/ai14') {
      if (-not $IncludeWorktree) { Write-Output 'DEFERRED: .g/ai14 registered worktree'; continue }
      # Remove links themselves with the native provider before Git removes the
      # obsolete checkout. Never recurse into a shared node_modules junction.
      & git -c core.longpaths=true worktree remove --force $absolute
      if ($LASTEXITCODE -ne 0) { throw 'Git worktree removal failed.' }
    } else {
      # PowerShell 7 removes directory junctions themselves rather than following
      # them; explicitly detach nested links first for a reviewable boundary.
      if ((Get-Item -LiteralPath $absolute -Force).PSIsContainer) {
        try { [IO.Directory]::Delete($absolute, $true) }
        catch [UnauthorizedAccessException] {
          # Git clone objects can carry read-only flags. The native provider
          # handles those within this same already-validated subtree.
          Remove-Item -LiteralPath $absolute -Recurse -Force
        }
      } else {
        Remove-Item -LiteralPath $absolute -Force
      }
    }
    [pscustomobject]@{path=$target.path; logicalBytes=$target.bytes; deletedAt=[DateTime]::UtcNow.ToString('o')} |
      ConvertTo-Json -Compress | Add-Content -LiteralPath (Join-Path $runEvidence 'deleted.jsonl')
    Write-Output "DELETED: $($target.path)"
  }
} finally { Pop-Location }
